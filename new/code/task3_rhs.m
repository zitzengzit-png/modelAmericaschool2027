function dydt = task3_rhs(t, y, p, sc, ts)
%TASK3_RHS  Right-hand side of the Task 3 intervention SEIQRD model.
%
%   States: [S;E;I;Q;R;D;M]
%   Lambda = S/N * phiV * phiPEP * (betaC*I + betaH*Q + betaF*D)

y = y(:);
S = y(1); E = y(2); I = y(3); Q = y(4); D = y(6);
% y(5)=R and y(7)=M do not appear in the RHS.

c  = task3_controls(t, sc, ts, p);
bc = p.betaC0 * (1 - p.u1 * (t >= p.t1)) * (1 - p.u2 * (t >= p.t2));

lam = S / p.N * c.phiV * c.phiPEP * ...
    (bc * c.bcMult * I + ...
     p.rhoH0 * bc * c.bhMult * Q + ...
     p.rhoF0 * bc * c.bfMult * D);

dydt = [ ...
    -lam; ...
     lam - p.sigma * E; ...
     p.sigma * E - (c.alpha + p.gamma + p.mu) * I; ...
     c.alpha * I - (p.gammaQ + c.muQ) * Q; ...
     p.gamma * I + p.gammaQ * Q; ...
     p.mu * I + c.muQ * Q - c.nu * D; ...
     p.mu * I + c.muQ * Q];
end
